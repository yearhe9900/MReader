// ══════════════════════════════════════════════════════════════════════════════
// ⚠️ **本节作废了 2026-10-12 从压缩录屏抽帧得到的那一版**（对比见下）。
// 原生截图分辨率高、无二次压缩噪声，是唯一可信的测量源。
//
// ── 几何（逐 px 实测，非目测）───────────────────────────────────────────────
//   选中块  x 57..266（**宽 210**）  y 1743..1857（**高 115**）
//   栏体    x 26..853（宽 828）      y 1742..1865（**高 124**）
//   标签中心 x = 163 / 347 / 532 / 715 ⇒ 间距 **184 / 185 / 183**（严格等分）
//   左右外边距 = 13.0 / 13.5 dp（对称）；底边距 = 27.5 dp
//   选中块中心 161.5 vs 第 1 格中心 163 ⇒ **差 1.5px，对齐**
//
// ── 材质（真实 RGB）────────────────────────────────────────────────────────
//   栏体空处  lum 23~25rgb(16,17,22)类← 近乎中性
//   选中块内  lum **74**  rgb(**74,74,74**)  ← **R=G=B 纯中性灰，无色偏**
//   边界过渡76→68→52→42（**2~3px**）
//
// ⚠️ **与 2026-10-12 那版的关键矛盾及裁决**
//
// ┌────────────────────┬───────────────┬────────────────┐
// │                    │ 10-12 压缩帧 │ 10-13 原生截图│
// ├────────────────────┼───────────────┼────────────────┤
// │ 选中块/格宽         │ 69%           │ **114%**       │
// │ 选中块 lum│ 52            │ **74**             │
// │ 选中块 RGB          │ (47,52,58)冷蓝│ **(74,74,74) 中性**│
// │ 选中块/栏高         │ 未测          │ **93%**        │
// └────────────────────┴───────────────┴────────────────┘
//
// **裁决：10-12 那版量错了，作废。** 两个独立证据：
//   ① 压缩帧是**二次压缩**产物，低对比度大面积色块的边界被抹平 / 偏移；
//   ② 原生截图里选中块宽 210 > 格宽 184，**目视也明显是「几乎占满一格」的宽块**，
//     与10-12 得出的「69% 窄块」在视觉上根本不符。
// ⇒ 10-12 把「141/129 = 109%」当成量错对象去否定，其实**那个方向才是对的**；
//   错的只是它在此基础上又跑到了 94%。真正的值是 **114%**。
//
// ⚠️ **参考图底栏左右并不对称**：栏体实测宽 828，而按标签间距反推的 4 格共736，
// 差 92px（恰好一个格宽）⇒ 标签**不是**居中于栏体，而是整体偏右。这是该 app
// 自身的布局（首项为重点项）。**本项目不照抄**，仍取严格等分居中——「等分」
// 「选中块与标签对齐」两个实测特征被保留。

import 'dart:ui' show ImageFilter;

import 'package:flutter/widgets.dart';

import 'glass_scope.dart' show GlassScope;

/// 底部导航栏的几何与材质（单位：逻辑像素 dp）。
abstract final class NavBarStyle {
  // ── 栏体 ────────────────────────────────────────────────────────────────────
  /// 胶囊高度。
  ///
  /// 参考图原生截图实测栏体高 **124px@2x = 62dp**（y 1742..1865）。取**62**
  /// 逐px对齐。
  static const double barHeight = 62;

  /// 胶囊左右外边距。
  ///
  /// 实测左 13.0 / 右 13.5 dp（对称）⇒ 取 **13**。
  static const double horizontalPadding = 13;

  /// 胶囊浮起高度（屏幕底边到胶囊底的距离）。
  ///
  /// 实测栏体底 y=1865 / 屏高 1920 ⇒ 底边距 55px@2x ≈ 27.5dp。取 **27**。
  static const double verticalPadding = 27;

  /// 胶囊圆角：栏体高 62 ⇒ 胶囊形 `r = 31`（实测四角内收与`h/2` 吻合）。
  static const double barRadius = 31;

  // ── 标签 ────────────────────────────────────────────────────────────────────
  /// 标签间的额外间距（`>0` 会挤占每格宽度，故取 0）。
  ///
  /// 实测标签中心严格等分 ⇒ 格子**不额外留缝**，每格占 `标签区宽 / n`。库默认的
  /// `spacing: 8` 正是破坏等分的元凶，这也是自研的一个直接收益。
  static const double tabSpacing = 0;

  /// 标签区左右**侧内缩**，占**一个格宽**的比例。
  ///
  /// ⭐ 实测（参考图原生截图）：标签区**并非占满栏体**，而是居中 + 左右各留
  /// 空白：
  ///
  /// ```text
  ///   栏体    x 26..853（宽 828）   标签中心 163/347/532/715（格宽 184）
  ///   标签区  x 71..807（宽 736）   ⇒ 侧留白 左 45 / 右 46
  ///   侧留白 / 格宽 = 0.2446 / 0.2500   （取 0.25）
  ///   标签区中心 439.0  vs 栏体中心 439.5  ⇒ 居中
  /// ```
  ///
  /// **为什么必须有它**：`pillWidthFactor = 1.14` 让选中块向两侧溢出格子。若标签
  /// 占满栏体，首/末格的选中块就会**贴到栏体边框甚至溢出**（这正是「触边」）。
  /// 加上侧内缩后，首格选中块左缘距栏体边缘稳定在 **11~14dp**（不随屏宽塌陷），
  /// 同时 pill 宽度不必改——**参考图就是「宽底衬 + 大边距」的组合**。
  ///
  /// ⚠️ **口径纠正**：上一批据「栏体 828 vs 标签反推 736，差 92px」判断「标签不
  /// 居中于栏体、整体偏右」，并据此判定「不照抄」。**那个结论是错的**——那 92px
  /// 其实是**左右各 46px 的侧留白**（标签区中心 439.0 vs 栏体中心 439.5，两侧
  /// 对称），不是一整格的偏移。⇒ 侧内缩是参考图的**真实特征**，本批照抄。
  ///
  /// 标签区宽解方程：`W + 2 × 0.25 × (W/n) = 可用宽` ⇒ `W = 可用宽 / (1 + 0.5/n)`。
  static const double sideInsetCellFactor = 0.25;

  /// 图标尺寸。
  static const double iconSize = 24;

  /// 图标与文字之间的间距。
  static const double iconLabelSpacing = 4;

  /// 标签文字字号。
  static const double labelFontSize = 11;

  // ── 选中块 ──────────────────────────────────────────────────────────────────
  /// 选中块宽度 = 格子宽的 **114%**（实测 210px / 184px）。
  ///
  /// 原生截图实测：选中块 x 57..266（宽 **210**），标签间距 **184** ⇒
  /// `210 / 184 = 1.141`。
  ///
  /// ⚠️ 这里有一段反复：2026-10-12 从**压缩录屏帧**量得 69%，据此把更早的
  /// 109% 判成「量错了对象」并改小；2026-10-13 用**原生截图**重测才发现
  /// **是压缩帧不可靠**——原生图里选中块明显是「几乎占满一格」的宽块
  /// （宽 210 > 格宽 184）。详见文件头的矛盾对照表。
  ///
  /// > 100% 意味着选中块**向两侧溢出**格子。实测这正是参考图的观感：宽底衬把
  /// 图标与文字整块托住，且相邻格的底衬之间留有明显空隙（格间距 - 溢出量）。
  static const double pillWidthFactor = 1.14;

  /// 选中块高度（占栏体高的比例）：实测 115 / 124 = **93%**。
  ///
  /// 几近撑满栏体高度——实测选中块距栏体上沿仅 **1px**、下沿 **8px**，是
  /// 「贴顶+ 微留底」的不对称留白，不是居中。
  static const double pillHeightFactor = 0.93;

  /// 选中块圆角：胶囊形 = 高的一半（实测高 115 ⇒ r≈57px ≈ 28.8dp）。
  static double pillRadius(double height) => height / 2;

  // ── 形变（切换时的液态拉伸）───────────────────────────────────────────────
  /// 切换动画时长（设计值；实测切换在 5.0s 前完成，视频 24fps 无法定毫秒级）。
  static const Duration switchDuration = Duration(milliseconds: 420);

  /// 切换曲线：`easeOutBack` 尾段回弹 ⇒ 选中块到位时有一次轻微过冲。
  ///
  /// 这是参考图「弹一下」的手感来源；纯 `easeOutCubic` 会显得死板。
  static const Curve switchCurve = Curves.easeOutBack;

  /// 拖动跟手形变的最大拉伸比例（选中块被拖动时横向拉宽）。
  static const double dragStretch = 0.18;

  // ── 材质（磨砂伪玻璃）──────────────────────────────────────────────────────
  /// 磨砂模糊sigma。
  ///
  /// 参考图的磨砂强度观感接近 iOS 的 `UIView` 毛玻璃档。Flutter 的 `sigma` 与
  /// 平台实现相关，取 **18** 是跨平台观感较稳的值（12~24 区间内差异不大）。
  static const double blurSigma = 18;

  /// 栏体纱罩不透明度（亮色下压到背景上的**白**）。
  ///
  /// 参考图底栏明显比背后内容「亮一档」——磨砂 + 白纱双叠加。亮色 **0.42**、
  /// 暗色 **0.10**（暗下面本已发亮，白纱要少）。
  static double scrimAlpha(Brightness brightness) =>
      brightness == Brightness.dark ? 0.10 : 0.42;

  /// 栏体边框不透明度（上缘一道亮边，是「玻璃有厚度」的关键视觉线索）。
  static const double barBorderAlpha = 0.28;

  /// 选中块纱罩不透明度。
  ///
  /// ⚠️ **2026-10-13 原生截图重测**：值由**反解**得出，不是拍的。实测栏体空处
  /// lum **23**，选中块内 lum **74**（≈3.2×）。纱罩取**中性灰**（见
  /// [pillScrimColor]，实测 R=G=B）时：
  ///
  /// ```text
  ///   23 + a × (255 − 23) = 74  ⇒  a = 0.22
  /// ```
  static double pillScrimAlpha(Brightness brightness) =>
      brightness == Brightness.dark ? 0.22 : 0.62;

  /// 选中块**描边**不透明度。
  ///
  /// 实测边界过渡只有 **2~3px**（`76 → 68 → 52 → 42`），是紧边界——**没有**
  /// 明显的亮描边。玻璃羽化由「磨砂 + 圆角」自然产生，叠加描边会得到一根白线。
  static const double pillBorderAlpha = 0.0;

  /// 标签文字颜色不透明度：选中 / 未选中。
  static const double selectedLabelAlpha = 0.95;
  static const double unselectedLabelAlpha = 0.62;

  /// 栏体的磨砂+纱罩合成（亮色主题下用）。
  ///
  /// 暗色下纱罩换成**黑色**提亮对比（暗面玻璃的正确做法：压黑而非加白）。
  static Color scrimColor(Brightness brightness) => brightness == Brightness.dark
      ? const Color(0xFF000000).withValues(alpha: scrimAlpha(Brightness.dark))
      : const Color(0xFFFFFFFF).withValues(alpha: scrimAlpha(Brightness.light));

  /// 选中块纱罩色。
  ///
  /// ⚠️ **2026-10-13 原生截图实测选中块 rgb(74,74,74) —— R=G=B，纯中性灰，
  /// 饱和度为 0**。此前据压缩帧定的「冷灰蓝 `0xFF9FB4C8`」是压缩帧的色偏产物，
  /// 作废。
  ///
  /// ⇒ 暗色与亮色都用**中性白**（靠 alpha 控亮度）；暗色下真正的颜色由
  /// [BackdropFilter] 采样到的**背后内容**决定——实测栏体右侧
  /// `rgb(56,30,43)` 透出粉色壁纸、`rgb(36,31,28)` 透出褐色，**这正是磨砂
  /// 透明的证据**：栏体颜色随背后内容变化，不是固定色。
  static Color pillScrimColor(Brightness brightness) =>
      const Color(0xFFFFFFFF).withValues(
        alpha: pillScrimAlpha(brightness),
      );

  /// 栏体磨砂滤镜。
  static ImageFilter barFilter(Brightness brightness) =>
      ImageFilter.blur(sigmaX: blurSigma, sigmaY: blurSigma);

  /// 选中块磨砂滤镜。
  ///
  /// 比栏体**更强**（参考图选中块背后内容更糊一档）⇒ sigma ×1.5。
  static ImageFilter pillFilter(Brightness brightness) => ImageFilter.blur(
        sigmaX: blurSigma * 1.5,
        sigmaY: blurSigma * 1.5,
      );

  /// 按当前亮度解析材质。
  ///
  /// 亮度走 [GlassScope.brightnessOf]（本作用域 → 库四级级联），与玻璃控件内部
  /// 同源（`UI-01` ②）。
  static Brightness brightnessOf(BuildContext context) =>
      GlassScope.brightnessOf(context);
}