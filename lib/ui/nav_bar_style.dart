// ⚠️ 本版**作废同日上一版**（那一版量的是 881×1920 的图，把栏体左右缘测错，
// 由此得出「圆角 15、不是胶囊」「侧内缩 0.25」两个错误结论）。
//
// ── 为什么确认上一版错了（两条独立证据）─────────────────────────────────────
//   ① **源图不同**：本版参考图 1220×2656 的栏体左右缘在 x 75..1144，
//      换算到 881 宽应为 x 54..826；上一版却写成 26..853。上一版把「栏体边缘」
//      测成了别的东西（差值 ~30px 且方向相反），据此反解出的侧内缩随之全错。
//   ② **可交叉验证的量全部吻合**：栏体上下缘 y2410..2581 换算到 881 宽 =
//      y1742..1865，与上一版记录的 y1742..1864 **逐像素吻合**；标签中心
//      226/481/737/991 换算后 = 163/347/532/715，与上一版的 163/347/532/715
//      **完全一致**；格宽 255↔184、标签区宽 1017.5↔736 也一致。
//      ⇒ 同一张图，上一版只在「栏体左右缘」这一项上量错，而侧内缩与圆角
//      两项结论都建立在该项之上。
//
// ── 栏体（逐 px 实测）────────────────────────────────────────────────────────
//   x 75..1144（宽 **1070**）  y 2410..2581（高 **171**）
//   左右外边距 75/76px = **27.3dp**（⚠️ 上一版按错误边缘得 13dp）
//   底边距 2656 − 2581 = 75px = **27.3dp**
//   ⭐ **圆角 = 高 / 2 = 85.5px = 31dp（胶囊）**——左缘剪影逐行拟合：
//      圆心 (161.5, 2495.5)、R=85.5，y2410/2444/2476/2514/2574 处预测
//      158/93/78/80/128 vs 实测 158/92/77/78/129，**偏差 ≤2px**。
//      栏体左右缘是圆弧而非直边 ⇒ 形态是**胶囊**，不是圆角矩形。
//   栏体空处 rgb(21,21,21)；本截图栏体背后是全黑（无内容可透出）。
//   四周一道 1~2px 亮边（左缘 x85 lum 49、右缘 x1135 lum 47 vs 栏体 21）。
//   ⚠️ **没有**「左右缘 15dp 宽高光带」——把 x 60..160 逐点打出来，
//      栏体从边缘内侧第 2px 起就稳定在 lum 20~21 直到标签。上一版测到的
//      「42px 宽、lum 185 的亮带」是压缩 / 边缘混淆的产物。
//
// ── 标签 ───────────────────────────────────────────────────────────────────
//   4 格中心 x = 228 / 482 / 736.5 / 991 ⇒ 间距 254 / 254.5 / 254.5（严格等分）
//   标签区 x 100.75..1118.25（宽 1017.5） 栏体中心 609.5 = 标签区中心 609.5
//   ⇒ 侧留白 (1070 − 1017.5) / 2 = **26.25px**，`26.25 / 255 = 0.103`（取 0.10）
//   图标宽实测 68px = **24.7dp**；文字行高对应字号 ≈ **12dp**；图标与文字
//   间距 ≈ 5dp。四个 tab 的图标与文字**颜色一致**（选中态只靠底衬区分）。
//   ⭐ 参考图 4 个 tab 的图标**全部是实心（filled）风格**，无描边。
//
// ── 选中块 ─────────────────────────────────────────────────────────────────
//   x 850..1135（宽 **286**）  y 2419..2571(高 **152**） 中心 (992.5, 2495)
//   圆角 = 高/2（胶囊形）：圆心 (926,2495)、R=76，y2419/2425/2440/2460/2486
//   处预测 926/896/874/859/850.5 vs 实测 926/894/872/857/849.5，**偏差 ≤2px**。
//   选中块内 rgb(49,49,49) 纯中性灰（R=G=B）。
//   格宽 255 ⇒ 宽 **286 = 格宽 × 1.12**（向两侧溢出格子）；
//   高 **152 / 171 = 0.89**；末格选中块右缘距栏体右缘仅 **9px = 3.3dp**。
//
// ── 手势指示条（**不是**选中块）──────────────────────────────────────────────
//   x 415..804（宽 390） y 2615..2631（高 17），在栏体**下方**的屏幕手势区。

import 'dart:ui' show ImageFilter;

import 'package:flutter/widgets.dart';

import 'glass_scope.dart' show GlassScope;

/// 底部导航栏的几何与材质（单位：逻辑像素 dp）。
abstract final class NavBarStyle {
  // ── 栏体 ────────────────────────────────────────────────────────────────────
  /// 栏体高度。
  ///
  /// 实测栏体 y2410..2581 = 171px@2.75 ≈ **62.2dp**（边缘柔化 ±1px），取 **62**。
  static const double barHeight = 62;

  /// 栏体左右外边距。
  ///
  /// ⭐ 实测左 75px / 右 76px ⇒ **27.3dp**，取 **28**（边缘柔化余量内）。
  ///
  /// ⚠️ 上一版按错误边缘得 13dp（栏体占屏宽 94%）；实测栏体只占 **87.7%**
  /// （1070 / 1220），左右各让出 28dp 才是参考图的「窄胶囊」观感。
  static const double horizontalPadding = 28;

  /// 栏体浮起高度（屏幕底边到栏体底的距离）。
  ///
  /// 实测 2656 − 2581 = 75px@2.75 ≈ 27.3dp，取 **27**。
  static const double verticalPadding = 27;

  /// 栏体圆角 = **高的一半**（胶囊）。
  ///
  /// ⭐ 实测 ≈ 85.5px = 31dp（左缘剪影逐行拟合，见文件头），而 62 / 2 = 31
  /// ⇒ 直接写成 `barHeight / 2`，改栏高时形态自动保持胶囊。
  ///
  /// ⚠️ 上一版定的 `15`（圆角矩形）是「还是没一比一复刻」的**主因**：它让栏体
  /// 两侧呈直角小圆角，而参考图是两端收成半圆的胶囊。
  static const double barRadius = barHeight / 2;

  // ── 标签 ────────────────────────────────────────────────────────────────────
  /// 标签间的额外间距（`>0` 会挤占每格宽度，故取 0）。
  ///
  /// 实测标签中心严格等分（254 / 254.5 / 254.5）⇒ 格子**不额外留缝**，每格占
  /// `标签区宽 / n`。库默认的 `spacing: 8` 正是破坏等分的元凶。
  static const double tabSpacing = 0;

  /// 标签区左右**侧内缩**，占**一个格宽**的比例。
  ///
  /// ⭐ 实测（参考图 1220×2656）：标签区并非占满栏体，而是居中 + 左右各留空白：
  ///
  /// ```text
  ///   栏体    x 75..1144（宽 1070）   标签中心 228/482/736.5/991（格宽 255）
  ///   标签区  x 100.75..1118.25（宽 1017.5）  ⇒ 侧留白 25.75 / 25.75
  ///   侧留白 / 格宽 = 26.25 / 255 = 0.103   （取 0.10）
  /// ```
  ///
  /// **为什么必须有它**：`pillWidthFactor = 1.12` 让选中块向两侧溢出格子。若标签
  /// 占满栏体，首/末格的选中块就会**贴到栏体边框甚至溢出**（这正是「触边」）。
  /// 加上侧内缩后，首格选中块左缘距栏体边缘稳定在 **3~4dp**，同时 pill 宽度不必改
  /// ——**参考图就是「溢出格子的宽底衬 + 栏体大边距」的组合**。
  ///
  /// 标签区宽解方程：`W + 2 × k × (W/n) = 可用宽` ⇒ `W = 可用宽 / (1 + 2k/n)`。
  ///
  /// ⚠️ 上一版据此得出 0.25（= 栏体边缘测错后的连带错误）。0.25 会把选中块从
  /// 栏体边缘推开到 13dp 以外，与参考图「几乎贴栏体边」的观感明显不符。
  static const double sideInsetCellFactor = 0.10;

  /// 图标尺寸。
  ///
  /// 实测图标 bbox 68px 宽（含抗锯齿）⇒ 24.7dp，取 **24**。
  static const double iconSize = 24;

  /// 图标与文字之间的间距。
  ///
  /// 实测图标底 y≈2500 / 文字顶 y≈2540 ⇒ 40px@2.75 ≈ 14dp 的行间空隙，
  /// 扣除图标字形与文字行高的内边距后取 **5dp**（与上一版一致，未变动）。
  static const double iconLabelSpacing = 5;

  /// 标签文字字号。
  ///
  /// 实测文字行高 33~35px@2.75（汉字几乎撑满 em 盒）⇒ ≈12dp。
  static const double labelFontSize = 12;

  // ── 选中块 ──────────────────────────────────────────────────────────────────
  /// 选中块宽度 = 格子宽的 **112%**（实测 286px / 255px）。
  ///
  /// 参考图实测：选中块 x 850..1135（宽 **286**），标签间距 **255** ⇒
  /// `286 / 255 = 1.122`。
  ///
  /// > 100% 意味着选中块**向两侧溢出**格子（各 15.5px）。实测这正是参考图的观感：
  /// 宽底衬把图标与文字整块托住，且相邻格的底衬之间留有明显空隙。
  static const double pillWidthFactor = 1.12;

  /// 选中块高度（占栏体高的比例）：实测 152 / 171 = **0.89**。
  ///
  /// 上下各留 9.5px = 3.5dp（居中）。
  static const double pillHeightFactor = 0.89;

  /// 选中块圆角：胶囊形 = 高的一半（实测高 152 ⇒ R=76px ≈ 27.6dp）。
  static double pillRadius(double height) => height / 2;

  // ── 形变（切换时的液态拉伸）───────────────────────────────────────────────
  /// 切换动画时长（设计值；实测切换在 5.0s 前完成，视频 24fps 无法定毫秒级）。
  static const Duration switchDuration = Duration(milliseconds: 420);

  /// 切换曲线：`easeOutBack` 尾段回弹 ⇒ 选中块到位时有一次轻微过冲。
  ///
  /// 这是参考图「弹一下」的手感来源；纯 `easeOutCubic` 会显得死板。
  static const Curve switchCurve = Curves.easeOutBack;

  /// 拖动跟手形变：**每拖过一格**，选中块横向拉宽的额外比例。
  ///
  /// 参考视频实测（592×1280，24fps，203 帧；栏体 `x41..578`、格宽 **129px**）：
  /// 取「逐像素 min 合成无 pill 背景 → 逐帧相减」把 pill 掩膜抠出来量 bbox。
  ///
  /// ```text
  ///   静止态宽 145（分类 / 我的两处静止帧一致）  ⇒ 145 / 129 = 1.12 = pillWidthFactor ✓
  ///   拖动中峰值宽 185（f0102、f0110）          ⇒ 185 / 145 = 1.28（总拉伸上限）
  /// ```
  ///
  /// 拖过 1 格时测得宽 ≈ 150~160（`150/145 ≈ 1.03`）⇒ 每格约 **0.15~0.20**，取 0.18。
  static const double dragStretchPerCell = 0.18;

  /// 拉伸上限（比例）。
  ///
  /// ⭐ 实测 `185 / 145 − 1 ≈ 0.28`，取 **0.30**（含压缩噪声余量）。
  ///
  /// ⚠️ 0.30 ⇒ 最宽 `1.12 × 1.30 = 1.456` 倍格宽。此前若按「约 2 倍格宽」取值会
  /// 把选中块拉成一根长条——那是**逐列亮度剖面**把图标列（lum 240+）误圈进来的
  /// 产物，与抠掩膜量出的 bbox 不符。
  static const double dragStretchMax = 0.30;

  // ── 材质（磨砂伪玻璃）──────────────────────────────────────────────────────
  /// 磨砂模糊sigma。
  ///
  /// 参考图的磨砂强度观感接近 iOS 的 `UIView` 毛玻璃档。Flutter 的 `sigma` 与
  /// 平台实现相关，取 **18** 是跨平台观感较稳的值（12~24 区间内差异不大）。
  static const double blurSigma = 18;

  /// 栏体纱罩不透明度（暗色下压在背景上的**白**）。
  ///
  /// 由实测**反解**：本截图栏体背后是全黑，栏体空处 lum **21**：
  ///
  /// ```text
  ///   0 + a × (255 − 0) = 21  ⇒  a ≈ 0.082   （取 0.08）
  /// ```
  ///
  /// 亮色档 **0.42**（暗色参考截图无亮色样本，沿用观感档）。
  static double scrimAlpha(Brightness brightness) =>
      brightness == Brightness.dark ? 0.08 : 0.42;

  /// 栏体**描边**不透明度（四周一道细亮边）。
  ///
  /// 实测栏体上缘 y2412 处 lum 46（栏体本体 21）⇒ 反解 alpha ≈ 0.107；
  /// 左右缘亮边 lum 47~55 同理。取 **0.12**。
  static const double barBorderAlpha = 0.12;

  /// 选中块纱罩不透明度。
  ///
  /// 由实测**反解**（不是拍的）：栏体空处 lum **21**、选中块内 lum **49**：
  ///
  /// ```text
  ///   21 + a × (255 − 21) = 49  ⇒  a = 28 / 234 ≈ 0.12
  /// ```
  ///
  /// ⚠️ 上一版的 0.215 是按「栏体 23 → 选中块 73」反解的，与本版实测
  /// （21 → 49）差近一倍——同一张图、同一反解公式，说明上一版把**选中块的
  /// 采样位置**取到了图标上（图标 lum 240+，会拉高采样值）。
  ///
  /// 亮色档取 **0.10 压黑**（不是加白）：栏体在亮色下已被白纱 0.42 提亮，
  /// 若选中块再加白纱会**几乎不可见**。参考图只有暗色样本，亮色这一档
  /// 是按「选中块相对栏体必须更显」的必要条件推的。
  static double pillScrimAlpha(Brightness brightness) =>
      brightness == Brightness.dark ? 0.12 : 0.10;

  /// 选中块**描边**不透明度。
  ///
  /// 实测边界过渡只有 **2~3px**，是紧边界——**没有**明显亮描边。玻璃羽化由
  /// 「磨砂 + 圆角」自然产生，叠加描边会得到一根白线。
  static const double pillBorderAlpha = 0.0;

  /// 标签文字颜色不透明度：选中 / 未选中。
  ///
  /// 实测参考图**选中与未选中的图标/文字颜色几乎一致**（四个标签的图标与文字
  /// 亮度中位数差在测量噪声内）⇒ 选中态只靠底衬区分。这里仍留一档极小差
  /// 异供无障碍/聚焦可辨，不改变观感。
  static const double selectedLabelAlpha = 0.85;
  static const double unselectedLabelAlpha = 0.80;

  /// 图标颜色不透明度：选中 / 未选中（同样几乎无差异）。
  static const double selectedIconAlpha = 0.95;
  static const double unselectedIconAlpha = 0.92;

  /// 栏体的磨砂+纱罩合成（亮色主题下用）。
  ///
  /// 暗色下纱罩换成**黑色**提亮对比（暗面玻璃的正确做法：压黑而非加白）。
  static Color scrimColor(Brightness brightness) => brightness == Brightness.dark
      ? const Color(0xFF000000).withValues(alpha: scrimAlpha(Brightness.dark))
      : const Color(0xFFFFFFFF).withValues(alpha: scrimAlpha(Brightness.light));

  /// 选中块纱罩色。
  ///
  /// 实测选中块 rgb(49,49,49) —— R=G=B，**纯中性灰**，饱和度为 0。
  /// ⇒ 暗色用**中性白**（靠 alpha 控亮度）；亮色用**中性黑**压暗。
  /// 暗色下真正的颜色由 [BackdropFilter] 采样到的**背后内容**决定——栏体颜色随
  /// 背后内容变化，不是固定色。
  static Color pillScrimColor(Brightness brightness) => brightness == Brightness.dark
      ? const Color(0xFFFFFFFF).withValues(alpha: pillScrimAlpha(brightness))
      : const Color(0xFF000000).withValues(alpha: pillScrimAlpha(brightness));

  /// 栏体磨砂滤镜。
  static ImageFilter barFilter(Brightness brightness) =>
      ImageFilter.blur(sigmaX: blurSigma, sigmaY: blurSigma);

  /// 选中块磨砂滤镜。
  ///
  /// 比栏体**更强**（参考图选中块背后内容更糊一档）⇒ sigma ×1.5。
  static ImageFilter pillFilter(Brightness brightness) => ImageFilter.blur(
        sigmaX: blurSigma * 1.5,
        sigmaY: blurSigma * 1.5,
      );

  /// 按当前亮度解析材质。
  ///
  /// 亮度走 [GlassScope.brightnessOf]（本作用域 → 库四级级联），与玻璃控件内部
  /// 同源（`UI-01` ②）。
  static Brightness brightnessOf(BuildContext context) =>
      GlassScope.brightnessOf(context);
}
