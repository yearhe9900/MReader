// ⚠️ 本版**作废 2026-10-12 从压缩录屏抽帧得到的那一版**（对比见下）。
// 原生截图分辨率高、无二次压缩噪声，是唯一可信的测量源。
//
// ── 栏体（逐 px 实测）────────────────────────────────────────────────────────
//   x 26..853（宽 828）   y 1742..1864（高 122）  左右外边距 26px = **13dp**
//   底边距 1920 − 1864 = 56px ≈ **28dp**
//   **圆角 ≈ 30px = 15dp**——右下角剪影拟合：弧从 (853,1850) 内收到
//   (812,1864)，y1848~1855 段与 R=30px 圆弧吻合（偏差 <3px）。
//   ⚠️ **不是胶囊**：10-12 那版据压缩帧把圆角定成 `h/2 = 31dp`，与原生图
//   直边的左/右缘（x26/x853 从顶到底基本直行）严重不符——这是「还是没
//   一比一复刻」的主要可见差异。
//   栏体空处 rgb(21,22,27) lum **23**；右侧透出背后壁纸的粉/紫色
//   （rgb(182,113,116) 等）⇒ 磨砂透明的直接证据。
//
// ── 选中块 ─────────────────────────────────────────────────────────────────
//   x 57..266（宽 210）   y 1743..1857（高 115）  中心 (161.5, 1800)
//   圆角 = 高/2（胶囊形，左缘弯曲与 r≈57px 预测吻合）
//   选中块内 rgb(**73,73,73**) 纯中性灰（R=G=B，饱和度 0）
//   首格格宽 184 ⇒ 宽 210 = 格宽 × **1.14**（向两侧溢出格子）
//
// ── 标签 ───────────────────────────────────────────────────────────────────
//   标签中心 x = 163 / 347 / 532 / 715 ⇒ 间距 184/185/183（严格等分）
//   标签区 x 72..808（宽 736）居中于栏体 ⇒ 侧留白 46/45 ≈ **0.25 格宽**
//   图标 24dp（实测 bbox 39~50px 宽 / 47~52px 高）；文字行高 23~24px ≈ 12dp
//   图标与文字间距实测 11px ≈ 5dp；内容整体垂直居中（上下各留 ~9dp）
//   **选中/未选中的图标与文字颜色几乎一致**（图标 alpha≈0.95、文字
//   alpha≈0.82，实测中位数 242~247 / 215~223）⇒ 选中态**只靠灰底衬区分**。
//
// ── 栏体左右缘高光带（本版新增实测特征）────────────────────────────────────
//   左缘有一条中性灰高光带：y1755 处 x26..68 宽 42px、lum **185**；
//   y1819 处 x26..52、lum 117；y1850 处 x26..60、lum 85。
//   右缘同理（被背后壁纸染色）。高光带**锐边**（4px 过渡）⇒ 是设计元素，
//   不是背后内容的模糊边界（磨砂羽化应有 ~36px 过渡）。
//
// ── 手势指示条（**不是**选中块，曾误判）────────────────────────────────────
//   x 297..578（宽 282） y 1887..1899（高 13） rgb(133,133,133)，
//   在栏体**下方**的屏幕手势区。10-13 上午那轮测量把它当成「选中块」，
//   得出「通栏贴边 / 13px 细条 / 选中项是第 3 格」三个错误结论，已作废。
//
// ⚠️ **与 2026-10-12 那版的关键矛盾及裁决**
//
// ┌────────────────────┬───────────────┬────────────────┐
// │                    │ 10-12 压缩帧 │ 10-13 原生截图│
// ├────────────────────┼───────────────┼────────────────┤
// │ 栏体圆角            │ h/2 = 31dp   │ **≈15dp**      │
// │ 选中块/格宽         │ 69%           │ **114%**       │
// │ 选中块 lum          │ 52            │ **74**(实测73) │
// │ 选中块 RGB          │ (47,52,58)冷蓝│ **(73,73,73)** │
// │ 选中块/栏高         │ 未测          │ **94%**        │
// └────────────────────┴───────────────┴────────────────┘
//
// **裁决：10-12 那版量错了，作废。** 两个独立证据：
//   ① 压缩帧是**二次压缩**产物，低对比度大面积色块的边界被抹平 / 偏移；
//   ② 原生截图里选中块宽 210 > 格宽 184，**目视也明显是「几乎占满一格」的宽块**，
//     与10-12 得出的「69% 窄块」在视觉上根本不符。
// ⇒ 10-12 把「141/129 = 109%」当成量错对象去否定，其实**那个方向才是对的**；
//   错的只是它在此基础上又跑到了 94%。真正的值是 **114%**。

import 'dart:ui' show ImageFilter;

import 'package:flutter/widgets.dart';

import 'glass_scope.dart' show GlassScope;

/// 底部导航栏的几何与材质（单位：逻辑像素 dp）。
abstract final class NavBarStyle {
  // ── 栏体 ────────────────────────────────────────────────────────────────────
  /// 栏体高度。
  ///
  /// 实测栏体 y1742..1864 = 122px@2x ≈ **61dp**（边缘柔化 ±1px），取 **62**。
  static const double barHeight = 62;

  /// 栏体左右外边距。
  ///
  /// 实测左 26px / 右 26~27px ⇒ **13dp**。
  static const double horizontalPadding = 13;

  /// 栏体浮起高度（屏幕底边到栏体底的距离）。
  ///
  /// 实测 1920 − 1864 = 56px@2x ≈ 28dp，取 **27**（边缘柔化余量内）。
  static const double verticalPadding = 27;

  /// 栏体圆角。
  ///
  /// ⭐ 原生截图实测 ≈ 30px = **15dp**（右下角剪影圆弧拟合，见文件头）。
  /// **不是胶囊**——10-12 那版据压缩帧定的 `h/2 = 31dp` 是「还是没复刻」
  /// 的主要可见差异：胶囊会让栏体两侧收成半圆，与参考图的直边+圆角
  /// 矩形形态完全不符。
  static const double barRadius = 15;

  // ── 标签 ────────────────────────────────────────────────────────────────────
  /// 标签间的额外间距（`>0` 会挤占每格宽度，故取 0）。
  ///
  /// 实测标签中心严格等分 ⇒ 格子**不额外留缝**，每格占 `标签区宽 / n`。库默认的
  /// `spacing: 8` 正是破坏等分的元凶，这也是自研的一个直接收益。
  static const double tabSpacing = 0;

  /// 标签区左右**侧内缩**，占**一个格宽**的比例。
  ///
  /// ⭐ 实测（参考图原生截图）：标签区**并非占满栏体**，而是居中 + 左右各留
  /// 空白：
  ///
  /// ```text
  ///   栏体    x 26..853（宽 828）   标签中心 163/347/532/715（格宽 184）
  ///   标签区  x 72..808（宽 736）   ⇒ 侧留白 左 46 / 右 45
  ///   侧留白 / 格宽 = 0.25 / 0.2446   （取 0.25）
  ///   标签区中心 440.0  vs 栏体中心 439.5  ⇒ 居中
  /// ```
  ///
  /// **为什么必须有它**：`pillWidthFactor = 1.14` 让选中块向两侧溢出格子。若标签
  /// 占满栏体，首/末格的选中块就会**贴到栏体边框甚至溢出**（这正是「触边」）。
  /// 加上侧内缩后，首格选中块左缘距栏体边缘稳定在 **11~14dp**（不随屏宽塌陷），
  /// 同时 pill 宽度不必改——**参考图就是「宽底衬 + 大边距」的组合**。
  ///
  /// 标签区宽解方程：`W + 2 × 0.25 × (W/n) = 可用宽` ⇒ `W = 可用宽 / (1 + 0.5/n)`。
  static const double sideInsetCellFactor = 0.25;

  /// 图标尺寸。
  ///
  /// 实测图标 bbox 39~50px 宽 / 47~52px 高（含抗锯齿）⇒ 24~25dp，取 **24**。
  static const double iconSize = 24;

  /// 图标与文字之间的间距。
  ///
  /// 实测图标底 y≈1812 / 文字顶 y≈1823 ⇒ 11px@2x ≈ 5dp。
  static const double iconLabelSpacing = 5;

  /// 标签文字字号。
  ///
  /// 实测文字行高 23~24px@2x（汉字几乎撑满 em 盒）⇒ ≈12dp。
  static const double labelFontSize = 12;

  // ── 选中块 ──────────────────────────────────────────────────────────────────
  /// 选中块宽度 = 格子宽的 **114%**（实测 210px / 184px）。
  ///
  /// 原生截图实测：选中块 x 57..266（宽 **210**），标签间距 **184** ⇒
  /// `210 / 184 = 1.141`。
  ///
  /// ⚠️ 这里有一段反复：2026-10-12 从**压缩录屏帧**量得 69%，据此把更早的
  /// 109% 判成「量错了对象」并改小；2026-10-13 用**原生截图**重测才发现
  /// **是压缩帧不可靠**——原生图里选中块明显是「几乎占满一格」的宽块
  /// （宽 210 > 格宽 184）。详见文件头的矛盾对照表。
  ///
  /// > 100% 意味着选中块**向两侧溢出**格子。实测这正是参考图的观感：宽底衬把
  /// 图标与文字整块托住，且相邻格的底衬之间留有明显空隙（格间距 - 溢出量）。
  static const double pillWidthFactor = 1.14;

  /// 选中块高度（占栏体高的比例）：实测 115 / 122 = **94%**。
  ///
  /// 几近撑满栏体高度——实测选中块距栏体上沿仅 **1px**、下沿 **7px**，是
  /// 「贴顶+ 微留底」的不对称留白（柔化边缘测量噪声 ±2px 内，实现取居中）。
  static const double pillHeightFactor = 0.93;

  /// 选中块圆角：胶囊形 = 高的一半（实测高 115 ⇒ r≈57px ≈ 28.8dp）。
  static double pillRadius(double height) => height / 2;

  // ── 形变（切换时的液态拉伸）───────────────────────────────────────────────
  /// 切换动画时长（设计值；实测切换在 5.0s 前完成，视频 24fps 无法定毫秒级）。
  static const Duration switchDuration = Duration(milliseconds: 420);

  /// 切换曲线：`easeOutBack` 尾段回弹 ⇒ 选中块到位时有一次轻微过冲。
  ///
  /// 这是参考图「弹一下」的手感来源；纯 `easeOutCubic` 会显得死板。
  static const Curve switchCurve = Curves.easeOutBack;

  /// 拖动跟手形变的最大拉伸比例（选中块被拖动时横向拉宽）。
  static const double dragStretch = 0.18;

  // ── 材质（磨砂伪玻璃）──────────────────────────────────────────────────────
  /// 磨砂模糊sigma。
  ///
  /// 参考图的磨砂强度观感接近 iOS 的 `UIView` 毛玻璃档。Flutter 的 `sigma` 与
  /// 平台实现相关，取 **18** 是跨平台观感较稳的值（12~24 区间内差异不大）。
  static const double blurSigma = 18;

  /// 栏体纱罩不透明度（亮色下压到背景上的**白**）。
  ///
  /// 参考图底栏明显比背后内容「亮一档」——磨砂 + 白纱双叠加。亮色 **0.42**、
  /// 暗色 **0.10**（暗下面本已发亮，白纱要少）。
  static double scrimAlpha(Brightness brightness) =>
      brightness == Brightness.dark ? 0.10 : 0.42;

  /// 栏体**描边**不透明度（顶/底缘一道细亮边）。
  ///
  /// 实测顶/底缘亮边只有 2~3px、lum 40~62（对栏体 23 反解 alpha ≈ 0.09~0.16），
  /// 比左右缘高光带弱一档——取 **0.12**。左右缘的亮带另有 [edgeGlowAlpha]。
  static const double barBorderAlpha = 0.12;

  /// 左右缘**高光带**宽度（从栏体左/右缘向内）。
  ///
  /// 实测左缘亮带：y1755 处 42px、y1819 处 26px、y1850 处 30px ⇒ 13~21dp，
  /// 取 **15dp**（带的外沿锐利、向内柔缓淡出）。
  static const double edgeGlowWidth = 15;

  /// 左右缘高光带亮度（白纱罩 alpha）。
  ///
  /// 由实测反解：栏体 23 + a×(255−23) = 117（y1819 处亮带）⇒ a ≈ **0.40**。
  /// y1755 处亮带更亮（185）是背后卡片内容较亮透出所致，非高光本身更强。
  static const double edgeGlowAlpha = 0.40;

  /// 选中块纱罩不透明度。
  ///
  /// ⚠️ **2026-10-13 原生截图重测**：暗色值由**反解**得出，不是拍的。实测栏体
  /// 空处 lum **23**、选中块内 lum **73**：
  ///
  /// ```text
  ///   23 + a × (255 − 23) = 73  ⇒  a = 50 / 232 ≈ 0.215
  /// ```
  ///
  /// 亮色档取 **0.10 压黑**（不是加白）：栏体在亮色下已被白纱 0.42 提亮，
  /// 若选中块再加白纱会**几乎不可见**。参考图只在暗色下有实测值，亮色这一档
  /// 是按「选中块相对栏体必须更显」的必要条件推的，**等拿到亮色参考截图后
  /// 需重新反解**。
  static double pillScrimAlpha(Brightness brightness) =>
      brightness == Brightness.dark ? 0.215 : 0.10;

  /// 选中块**描边**不透明度。
  ///
  /// 实测边界过渡只有 **2~3px**（`76 → 68 → 52 → 42`），是紧边界——**没有**
  /// 明显的亮描边。玻璃羽化由「磨砂 + 圆角」自然产生，叠加描边会得到一根白线。
  static const double pillBorderAlpha = 0.0;

  /// 标签文字颜色不透明度：选中 / 未选中。
  ///
  /// 实测参考图**选中与未选中的图标/文字颜色几乎一致**（文字中位数
  /// 215~223、图标 242~247）⇒ 选中态只靠灰底衬区分。这里仍留一档极小差
  /// 异供无障碍/聚焦可辨，不改变观感。
  static const double selectedLabelAlpha = 0.85;
  static const double unselectedLabelAlpha = 0.80;

  /// 图标颜色不透明度：选中 / 未选中（实测 ≈0.95，同样几乎无差异）。
  static const double selectedIconAlpha = 0.95;
  static const double unselectedIconAlpha = 0.92;

  /// 栏体的磨砂+纱罩合成（亮色主题下用）。
  ///
  /// 暗色下纱罩换成**黑色**提亮对比（暗面玻璃的正确做法：压黑而非加白）。
  static Color scrimColor(Brightness brightness) => brightness == Brightness.dark
      ? const Color(0xFF000000).withValues(alpha: scrimAlpha(Brightness.dark))
      : const Color(0xFFFFFFFF).withValues(alpha: scrimAlpha(Brightness.light));

  /// 选中块纱罩色。
  ///
  /// ⚠️ **2026-10-13 原生截图实测选中块 rgb(73,73,73) —— R=G=B，纯中性灰，
  /// 饱和度为 0**。此前据压缩帧定的「冷灰蓝 `0xFF9FB4C8`」是压缩帧的色偏产物，
  /// 作废。
  ///
  /// ⇒ 暗色用**中性白**（靠 alpha 控亮度）；亮色用**中性黑**压暗（见
  /// [pillScrimAlpha] 的说明）。暗色下真正的颜色由 [BackdropFilter] 采样到的
  /// **背后内容**决定——实测栏体右侧 `rgb(182,113,116)` 透出粉色壁纸、
  /// `rgb(64,51,58)` 透出褐色，**这正是磨砂透明的证据**：栏体颜色随背后内容
  /// 变化，不是固定色。
  static Color pillScrimColor(Brightness brightness) => brightness == Brightness.dark
      ? const Color(0xFFFFFFFF).withValues(alpha: pillScrimAlpha(brightness))
      : const Color(0xFF000000).withValues(alpha: pillScrimAlpha(brightness));

  /// 栏体**左右缘高光带**的渐变。
  ///
  /// 参考图左右缘各有一条中性灰亮带（实测 lum 117~185 vs 栏体 23），外沿锐
  /// 利、向内 15dp 柔缓淡出——是「玻璃有厚度」的关键视觉线索。亮带亮度基本
  /// 不随高度变化（差异来自背后内容明暗），故只需水平渐变。
  ///
  /// [barWidth] 为栏体可用宽（已扣左右外边距），用于把 [edgeGlowWidth] 换算
  /// 成渐变 stop。
  static LinearGradient edgeGlowGradient(double barWidth) {
    // ⚠️ 本文件只 import `widgets.dart`，**`Colors` 不可用**（它在 material 导出）。
    // 故一律用显式 `Color` 字面量，别图省事写 `Colors.white`。
    const Color glow = Color(0xFFFFFFFF);
    if (barWidth <= 0) {
      return const LinearGradient(colors: <Color>[Color(0x00000000)]);
    }
    final double stop = (edgeGlowWidth / barWidth).clamp(0.0, 0.5);
    return LinearGradient(
      begin: Alignment.centerLeft,
      end: Alignment.centerRight,
      colors: <Color>[
        glow.withValues(alpha: edgeGlowAlpha),
        const Color(0x00000000),
        const Color(0x00000000),
        glow.withValues(alpha: edgeGlowAlpha),
      ],
      stops: <double>[0, stop, 1 - stop, 1],
    );
  }

  /// 栏体磨砂滤镜。
  static ImageFilter barFilter(Brightness brightness) =>
      ImageFilter.blur(sigmaX: blurSigma, sigmaY: blurSigma);

  /// 选中块磨砂滤镜。
  ///
  /// 比栏体**更强**（参考图选中块背后内容更糊一档）⇒ sigma ×1.5。
  static ImageFilter pillFilter(Brightness brightness) => ImageFilter.blur(
        sigmaX: blurSigma * 1.5,
        sigmaY: blurSigma * 1.5,
      );

  /// 按当前亮度解析材质。
  ///
  /// 亮度走 [GlassScope.brightnessOf]（本作用域 → 库四级级联），与玻璃控件内部
  /// 同源（`UI-01` ②）。
  static Brightness brightnessOf(BuildContext context) =>
      GlassScope.brightnessOf(context);
}
